export type UsStateCode = (typeof US_STATES)[number]['code'];

const BY_CODE = new Map<string, (typeof US_STATES)[number]>(
  US_STATES.map((state) => [state.code, state]),
);

const BY_NAME = new Map<string, (typeof US_STATES)[number]>(
  US_STATES.map((state) => [state.name.toLowerCase(), state]),
);

/** Older profiles stored weather codes (ny) or a full name. Both become a postal code. */
export function homeStateCode(value: string | null | undefined): UsStateCode | null {
  const raw = (value ?? '').trim();
  if (!raw) return null;
  const byCode = BY_CODE.get(raw.toUpperCase());
  if (byCode) return byCode.code;
  const byName = BY_NAME.get(raw.toLowerCase());
  return byName?.code ?? null;
}

export function homeStateLabel(value: string | null | undefined): string | null {
  const code = homeStateCode(value);
  if (!code) return null;
  return BY_CODE.get(code)?.name ?? null;
}
